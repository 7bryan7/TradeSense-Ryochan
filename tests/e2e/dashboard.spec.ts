import { expect, test } from "@playwright/test";

test("creates a simulated decision and answers without changing chat into a trade", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Turn market evidence into a decision you can inspect." })).toBeVisible();
  await expect(page.getByText("Instant demo access · no Google account")).toBeVisible();
  await page.getByRole("button", { name: /Enter demo workspace/ }).click();
  await expect(page.getByText("No wallet. No real funds. All fills are simulated.")).toBeVisible();
  const marketOverview = page.getByRole("region", { name: "What is happening across the market?" });
  await expect(marketOverview).toContainText("No saved market overview");
  const paperCashHeading = page.locator(".portfolio-card").getByRole("heading");
  await expect(paperCashHeading).not.toHaveText("—");
  const initialPaperCash = await paperCashHeading.innerText();
  await marketOverview.getByRole("button", { name: "Fetch overview" }).click();
  await expect(marketOverview).toContainText("Fixture market breadth is positive with moderate greed");
  await expect(marketOverview).toContainText("Market regime");
  await expect(marketOverview).toContainText("risk-on");
  await expect(marketOverview).toContainText("SOL");
  await expect(marketOverview).toContainText("Synthetic fixture data for offline development");
  await expect(paperCashHeading).toHaveText(initialPaperCash);
  await page.keyboard.press("Shift+/");
  const shortcutsDialog = page.getByRole("dialog", { name: "Keyboard shortcuts" });
  await expect(shortcutsDialog).toContainText("Analysis and scheduling remain deliberate button actions.");
  await page.keyboard.press("Escape");
  await expect(shortcutsDialog).not.toBeVisible();
  await page.keyboard.press("g");
  await page.keyboard.press("h");
  await expect(page).toHaveURL(/\?view=history$/);
  await page.keyboard.press("g");
  await page.keyboard.press("o");
  await expect(page).toHaveURL(/\?view=dashboard$/);
  const runWorkflow = page.getByRole("region", { name: "Research to audit trail" });
  await expect(runWorkflow).toContainText("NO SAVED RUN");
  await page.getByRole("button", { name: "Analyze & simulate" }).click();
  await expect(page.locator("#decision-heading")).toHaveText("BUY");
  await expect(runWorkflow.locator(".workflow-step.complete")).toHaveCount(4);
  await expect(runWorkflow).toContainText("APPLIED · BUY");
  await expect(runWorkflow).toContainText("Stages reflect saved records, not inferred provider activity.");
  await expect(page.locator(".simulation-card")).toContainText("APPLIED");
  await expect(page.locator(".risk-line")).toContainText("RSI is approaching an overbought range");
  await expect(page.locator(".audit-line")).toContainText("Verified — saved result matches");
  await page.getByRole("button", { name: "View replay" }).click();
  const replayDialog = page.getByRole("dialog", { name: "Deterministic replay" });
  await expect(replayDialog).toContainText("Saved and recomputed results match");
  await expect(replayDialog).toContainText("Read-only verification · the paper portfolio was not changed.");
  await expect(replayDialog.getByText("SAVED RESULT", { exact: true })).toBeVisible();
  await expect(replayDialog.getByText("RECOMPUTED RESULT", { exact: true })).toBeVisible();
  await replayDialog.getByRole("button", { name: "Close dialog" }).click();
  const mainNavigation = page.getByRole("navigation", { name: "Main navigation" });
  await mainNavigation.getByRole("link", { name: "AI reasoning", exact: true }).click();
  await expect(page).toHaveURL(/\?view=analysis&run=[0-9a-f-]{36}$/);
  const toolTimeline = page.getByRole("region", { name: "Research tool timeline" });
  await expect(toolTimeline).toContainText("4 of 4 steps completed · 4 provider attempts");
  await expect(toolTimeline.locator(".tool-step-completed")).toHaveCount(4);
  await expect(toolTimeline).toContainText("SELECTED-TOKEN EVIDENCE");
  await expect(toolTimeline).toContainText("RISK COVERAGE");
  await expect(toolTimeline).toContainText("MARKET CONTEXT");
  await expect(toolTimeline).toContainText("BENCHMARK COMPARISON");
  await expect(toolTimeline).toContainText("SOL,BTC");
  await expect(toolTimeline).toContainText("Saved evidence · provider status ok");
  const evidenceLedger = page.getByRole("region", { name: "Saved evidence ledger" });
  await expect(evidenceLedger).toContainText("4 owned observations tied to this run.");
  await expect(evidenceLedger).toContainText("analyze_token");
  await expect(evidenceLedger).toContainText("deep_analysis");
  await expect(evidenceLedger).toContainText("scan_market");
  await expect(evidenceLedger).toContainText("compare_tokens");
  await evidenceLedger.locator("summary").first().click();
  await expect(evidenceLedger).toContainText("Evidence ID");
  await expect(evidenceLedger).toContainText("Synthetic fixture data for offline development");
  await mainNavigation.getByRole("link", { name: "Overview", exact: true }).click();
  await expect(page).toHaveURL(/\?view=dashboard$/);
  await expect(page.getByText("No candle series")).toBeVisible();
  await expect(page.locator(".comparison-strip")).toContainText("No comparable run yet");
  await page.getByRole("button", { name: "Analyze & simulate" }).click();
  await expect(page.locator(".comparison-strip")).toContainText("Compatible 24h evidence");
  await expect(page.locator(".portfolio-card")).toContainText("Total paper equity");
  await expect(page.locator(".portfolio-card")).toContainText("Valuation complete");
  await mainNavigation.getByRole("link", { name: "Decision history", exact: true }).click();
  await expect(page).toHaveURL(/\?view=history&run=[0-9a-f-]{36}$/);
  await expect(page.getByText("TOTAL ANALYSES", { exact: true }).locator("..")).toContainText("2");
  await expect(page.getByText("COMPLETED DECISIONS", { exact: true }).locator("..")).toContainText("2");
  await page.getByLabel("Filter history by decision").selectOption("HOLD");
  await expect(page.getByText("No matching decisions", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Clear filters" }).click();
  await expect(page.locator(".history-row:not(.history-head)")).toHaveCount(2);
  await page.getByLabel("Filter history by token").selectOption("SOL");
  await expect(page.locator(".history-row:not(.history-head)")).toHaveCount(2);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Decision history." })).toBeVisible();
  await expect(page).toHaveURL(/\?view=history&run=[0-9a-f-]{36}$/);
  await mainNavigation.getByRole("link", { name: "Overview", exact: true }).click();
  await expect(page).toHaveURL(/\?view=dashboard$/);
  await page.goBack();
  await expect(page.getByRole("heading", { name: "Decision history." })).toBeVisible();
  await mainNavigation.getByRole("link", { name: "Overview", exact: true }).click();
  const schedules = page.locator(".schedule-card");
  await expect(schedules).toContainText("WORKER ENABLED");
  await schedules.getByRole("button", { name: "Add 5m SOL schedule" }).click();
  await expect(schedules).toContainText("PAUSED");
  await schedules.getByRole("button", { name: "Resume" }).click();
  await expect(schedules).toContainText("ACTIVE");
  await schedules.getByRole("button", { name: "Pause" }).click();
  await expect(schedules).toContainText("PAUSED");
  const portfolioCard = page.locator(".portfolio-card");
  const cashAfterDecision = await portfolioCard.getByRole("heading").innerText();
  await mainNavigation.getByRole("link", { name: /Ask TradeSense/ }).click();
  const chatContext = page.getByRole("region", { name: "Chat research context" });
  await expect(chatContext).toContainText("SOL · BUY");
  await expect(chatContext).toContainText("FIXTURE");
  const chatComposer = page.getByLabel("Ask about the market");
  await chatComposer.focus();
  await page.keyboard.type("gh");
  await expect(chatComposer).toHaveValue("gh");
  await expect(page).toHaveURL(/\?view=chat$/);
  await chatComposer.fill("Why this decision?");
  await page.getByRole("button", { name: "Send question" }).click();
  await expect(page.getByText(/saved SOL decision was BUY/)).toBeVisible();
  await expect(page.locator(".source-list")).toContainText("RYO evidence");
  await page.getByRole("button", { name: "Check data coverage", exact: true }).click();
  await expect(page.getByLabel("Ask about the market")).toHaveValue("Which data is present, missing, or stale?");
  await mainNavigation.getByRole("link", { name: "Overview", exact: true }).click();
  await expect(page.locator(".portfolio-card").getByRole("heading")).toHaveText(cashAfterDecision);
  await page.reload();
  await expect(page.locator("#decision-heading")).toHaveText("BUY");
  await expect(page.getByRole("region", { name: "What is happening across the market?" })).toContainText("Fixture market breadth is positive with moderate greed");
  await expect(page.locator(".audit-line")).toContainText("Verified — saved result matches");
  await mainNavigation.getByRole("link", { name: /Ask TradeSense/ }).click();
  await expect(page.getByText(/saved SOL decision was BUY/)).toBeVisible();
  await mainNavigation.getByRole("link", { name: "Paper portfolio", exact: true }).click();
  await expect(page.getByText("VIRTUAL CASH", { exact: true }).locator("..")).toContainText(cashAfterDecision);
  const paperLedger = page.getByRole("region", { name: "Recent simulated transactions" });
  await expect(paperLedger).toContainText("2 of 2 records shown");
  await expect(paperLedger.getByText("APPLIED FILLS", { exact: true }).locator("..")).toContainText("2");
  await expect(paperLedger.locator(".paper-transaction")).toHaveCount(2);
  await paperLedger.getByLabel("Filter paper ledger").selectOption("nonfills");
  await expect(paperLedger.getByText("No matching simulation records", { exact: true })).toBeVisible();
  await paperLedger.getByLabel("Filter paper ledger").selectOption("applied");
  await expect(paperLedger.locator(".paper-transaction")).toHaveCount(2);
});
